def _embed_for_index(snap_id: str, body: str) -> Dict[str, Any]:
    """Schema-shaped embedding payload for append_snapshot_vectors (M6c).

    Delegates to search.embed_snapshot_for_index: a v1 active store yields
    {"embedding": [...]} (today's exact single whole-body vector), a v2 store
    yields {"chunk_vectors": [[...], ...]}, and ANY failure yields {} so the
    mint completes vector-less (catch-up re-embeds). This wrapper adds the
    journalctl-verifiable success/failure lines the mint-verification ritual
    greps for, and never raises — even an embeddings-stack import failure is
    a logged soft failure, never a broken mint.
    """
    try:
        # M7 ledger rule: a WELLNESS-tagged snapshot whose owner did not allow
        # the active embedder is embedded as its pointer line only.
        from Orchestrator.wellness import redact as wellness_redact
        body = wellness_redact.embed_text(body)
        # Lazy import (monitoring.py's delegate pattern): checkpoint is
        # imported very early at startup, before the embeddings stack.
        from Orchestrator.embeddings.search import embed_snapshot_for_index
        payload = embed_snapshot_for_index(body) or {}
    except Exception as e:
        print(f"[EMBEDDING] embedding layer unavailable for {snap_id}: {e}")
        payload = {}
    if payload.get("embedding"):
        print(f"[EMBEDDING] Successfully generated embedding ({len(payload['embedding'])} dimensions)")
    elif payload.get("chunk_vectors"):
        chunks = payload["chunk_vectors"]
        print(f"[EMBEDDING] Successfully generated embedding ({len(chunks[0])} dimensions, {len(chunks)} chunks)")
    else:
        print(f"[EMBEDDING] Warning: Failed to generate embedding for {snap_id}")
    return payload


def _best_effort(warnings: List[str], what: str, snap_id: str, fn, *args, **kwargs):
    """Run one post-append step of a mint. The snapshot is already in the
    ledger (the commit point), so a failure here is logged loudly and
    reported in the result's "warnings", never raised: raising would make the
    caller treat a committed snapshot as unminted and mint its turns again
    (audit O05-ledger-persistence-04)."""
    try:
        return fn(*args, **kwargs)
    except Exception as e:
        print(f"[MINT] {what} failed for {snap_id} (the snapshot is in the ledger): {e}")
        warnings.append(f"{what}: {e}")
        return None


def _index_entry(warnings: List[str], snap_id: str, *args, **kwargs) -> None:
    """The snapshot's index entry, under mint_lock: two writers must never
    read-modify-write the index at once. Vectors are appended separately,
    after the lock is released."""
    if not _best_effort(warnings, "snapshot index", snap_id, update_snapshot_index, snap_id, *args, **kwargs):
        if not any(w.startswith("snapshot index") for w in warnings):
            warnings.append("snapshot index: the entry was not written (see the journal)")


def _ledger_record(warnings: List[str], snap_id: str, byte_start: int, byte_end: int,
                   utc: str) -> Optional[Dict[str, Any]]:
    """The append's prefix-hash record (volume.record_append: the sha256 of
    the ledger as this append left it, one line of Manifest/ledger_hashes.jsonl),
    under mint_lock so the records follow the appends in order. It replaces
    the full ledger copy every mint wrote into Archive/ (audit
    O05-ledger-persistence-02); full copies are scheduled now. Best-effort:
    the snapshot is already committed."""
    return _best_effort(warnings, "ledger hash record", snap_id, record_append,
                        snap_id, byte_start, byte_end, utc, ledger_path=VOL_PATH)


def _mint_result(snap_id: str, record: Optional[Dict[str, Any]], byte_end: int) -> Dict[str, Any]:
    """The fields every mint result carries about the ledger: assert_sha256
    is the sha256 of the ledger as this mint committed it (what the per-mint
    archive copy's digest was), archived is None (mints make no copy any
    more; the maintenance pass makes one a day), ledger_bytes its size."""
    return {"snap_id": snap_id,
            "assert_sha256": record["sha256"] if record else None,
            "archived": None,
            "ledger_bytes": byte_end}


def _embed_and_store(warnings: List[str], snap_id: str, body: str) -> Optional[int]:
    """Embed a committed snapshot and append its vectors, outside mint_lock
    (audit O05-ledger-persistence-05: an embed is bounded only by the search
    layer's ceiling, minutes on a degraded provider, and every other mint used
    to queue behind it). A failure leaves the snapshot vector-less, which the
    catch-up loop (store.missing()) re-embeds. Returns the embedding dims."""
    print(f"[EMBEDDING] Generating embedding for snapshot {snap_id}...")
    embed_payload = _embed_for_index(snap_id, body)
    if not embed_payload:
        return None
    _best_effort(warnings, "vector store", snap_id, append_snapshot_vectors, snap_id, **embed_payload)
    # Task 1.4: surface the embedding dimension (the SAME value
    # _embed_for_index logged) so /chat/save can feed the mint telemetry line.
    if embed_payload.get("embedding"):
        return len(embed_payload["embedding"])
    return len(embed_payload["chunk_vectors"][0])


