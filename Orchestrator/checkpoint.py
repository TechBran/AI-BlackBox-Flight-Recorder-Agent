# volume.py raises its framework-free LedgerError (GM missing or altered, torn
# ledger tail); a route that lets one escape answers 500 with the same detail
# the HTTPException it replaced carried.
@app.exception_handler(LedgerError)
async def _ledger_error_response(_request, exc: LedgerError):
    from fastapi.responses import JSONResponse
    return JSONResponse(status_code=500, content={"detail": exc.detail})

