def _call_provider(provider: str, messages: List[Dict], model: str, operator: str) -> str:
    """One non-stream chat call; the reply text."""
    from Orchestrator.routes import chat_routes as cr  # lazy: import cycle
    if provider == "google":
        from Orchestrator.routes.chat_routes import call_gemini
        # call_gemini returns 5 elements (2-media adds media_tasks last).
        text, _usage, _, _, _ = call_gemini(messages, model=model, operator=operator)
        return text
    fn = {"anthropic": cr.call_anthropic, "openai": cr.call_openai,
          "xai": cr.call_xai, "custom": cr.call_custom}.get(provider)
    if fn is None:
        raise ValueError(f"no chat call for provider {provider!r}")
    out = fn(messages, model, operator)
    return out[0] if isinstance(out, tuple) else out


def _compress(prompt: str, operator: str):
    """(summary, model) from the configured provider, or (None, error).

    Order: config.ini [checkpoint] provider / model when set, then the box's
    DEFAULT_PROVIDER, then each other provider this box holds a key for; an
    empty or "Auto" model is that provider's configured default
    (resolve_default_model). It used to call a pinned gemini-3.1-pro-preview,
    which on a box without a Google key failed every turn after the first
    interval (audit O05-ledger-persistence-15).
    """
    import Orchestrator.config as _cfg
    messages = [{"role": "user", "content": prompt}]
    candidates = []
    cfg_provider = _cfg.CFG.get("checkpoint", "provider", fallback="").strip().lower()
    if cfg_provider:
        candidates.append((cfg_provider, _cfg.CFG.get("checkpoint", "model", fallback="").strip()))
    candidates.append((_cfg.DEFAULT_PROVIDER, ""))
    for provider, key in (("google", "GOOGLE_API_KEY"), ("anthropic", "ANTHROPIC_API_KEY"),
                          ("openai", "OPENAI_API_KEY"), ("xai", "XAI_API_KEY")):
        if getattr(_cfg, key, ""):
            candidates.append((provider, ""))
    tried = set()
    last_error = "no provider configured"
    for provider, model in candidates:
        provider = {"gemini": "google"}.get(provider, provider)
        if provider in tried:
            continue
        tried.add(provider)
        model = _cfg.resolve_default_model(provider, model)
        try:
            text = _call_provider(provider, messages, model, operator)
        except Exception as e:
            last_error = f"{provider}: {e}"
            print(f"[CHECKPOINT] Compression via {provider} failed: {e}")
            continue
        if text:
            return text, (model or provider)
        last_error = f"{provider}: empty reply"
    return None, last_error


def create_checkpoint_async(operator: str, manual: bool = False) -> Dict[str, Any]:
    """Create a compressed checkpoint snapshot for an operator.

    This function:
    1. Retrieves recent snapshots for the operator (count configured in [checkpoint] section)
    2. Sends them to the configured provider for compression (_compress)
    3. Saves the compressed summary as a checkpoint snapshot

    Args:
        operator: The operator name (e.g., "Alice", "Bob")
        manual: Whether this is a manual checkpoint (vs automatic at configured intervals)

    Returns:
        {"status": "created", "snap_id": ...}, {"status": "skipped", "reason": ...}
        or {"status": "failed", "error": ...}. Never raises.
    """
    with _checkpoints_lock:
        if operator in _checkpoints_in_flight:
            print(f"[CHECKPOINT] A checkpoint for {operator} is already being created; skipped")
            return {"status": "skipped", "reason": "a checkpoint for this operator is already being created"}
        _checkpoints_in_flight.add(operator)
    try:
        return _create_checkpoint(operator, manual)
    except Exception as e:
        print(f"[CHECKPOINT] Error creating checkpoint for {operator}: {e}")
        traceback.print_exc()
        return {"status": "failed", "error": str(e)}
    finally:
        with _checkpoints_lock:
            _checkpoints_in_flight.discard(operator)


def _create_checkpoint(operator: str, manual: bool) -> Dict[str, Any]:
    s = get_state(operator)

    # Get recent snapshots for this operator (configured in [checkpoint] section),
    # their byte ranges only: the helper reads the volume itself when there is
    # no index, and never used the whole decoded volume this used to pass it.
    # M7 ledger rule: the compressor is a background reader, so a WELLNESS-
    # tagged turn reaches it (and the summary everyone reads later) only as
    # "[wellness conversation · not shared]".
    from Orchestrator.wellness import redact as wellness_redact
    with wellness_redact.reading_as(wellness_redact.background_reader(operator)):
        recent_snapshots = get_recent_fossils_for_operator("", operator, count=CHECKPOINT_TURNS_TO_COMPRESS, cap_chars_each=10000)

    if len(recent_snapshots) < CHECKPOINT_MIN_SNAPSHOTS:
        print(f"[CHECKPOINT] Not enough snapshots for {operator} to create checkpoint ({len(recent_snapshots)}/{CHECKPOINT_TURNS_TO_COMPRESS})")
        return {"status": "skipped", "reason": f"only {len(recent_snapshots)} snapshots (need {CHECKPOINT_MIN_SNAPSHOTS})"}

    print(f"[CHECKPOINT] Creating checkpoint for {operator} with {len(recent_snapshots)} snapshots")

    # Prepare compression prompt
    snapshots_text = "\n\n" + "="*80 + "\n\n".join(recent_snapshots)

    compression_prompt = f"""Compress the following {len(recent_snapshots)} conversation turns into a detailed, coherent summary that preserves key context, decisions, technical details, and conversation flow.

Maintain enough detail that someone reading only this summary could continue the conversation meaningfully.

Focus on:
- Main topics discussed
- Decisions made
- Technical implementations
- User preferences expressed
- Important context that should be remembered
- Key problems solved
- System architecture details
- Feature requests and requirements

Provide a comprehensive, structured summary:

{snapshots_text}"""

    compressed_summary, model_used = _compress(compression_prompt, operator)

    if not compressed_summary:
        print(f"[CHECKPOINT] Failed to generate compression for {operator}: {model_used}")
        return {"status": "failed", "error": f"compression failed ({model_used})"}

    warnings: List[str] = []
    # Create checkpoint snapshot: render, append and index under the lock;
    # the embed runs after it is released (see _embed_and_store).
    with mint_lock:
        utc = now_utc_iso()
        info1 = parse_tail(read_tail_text(VOL_PATH))
        snap_id = next_snap_id_from_tail(info1["tail_id"])

        # Determine source range
        source_start = s.total_turns - len(recent_snapshots)
        source_end = s.total_turns

        reason = "MANUAL_CHECKPOINT" if manual else f"AUTO_CHECKPOINT_TURN_{s.total_turns}"

        # Build checkpoint snapshot body
        log_lines = [
            f"[CHECKPOINT] Compressed summary of {len(recent_snapshots)} snapshots",
            f"[CHECKPOINT] Source range: turns {source_start}-{source_end}",
            f"[CHECKPOINT] Operator: {operator}",
            "",
            compressed_summary
        ]

        gauges = {
            "drift": "green",
            "p": 0,
            "c": len(compressed_summary),
            "t": len(compressed_summary),
            "model": model_used,
            "operator": operator
        }

        provenance = {
            "gm": True,
            "recent": [],
            "relevant": []
        }

        # Render checkpoint snapshot with special metadata
        body = render_snapshot_body_v71(
            info=info1,
            snap_id=snap_id,
            utc=utc,
            reason=reason,
            log_lines=log_lines,
            gauges=gauges,
            provenance=provenance
        )

        # Add checkpoint-specific metadata
        body = body.replace("MODE: Normal", "MODE: Checkpoint")
        body = body.replace(f"OPERATOR: {operator}", f"OPERATOR: {operator}\nTYPE: checkpoint\nSOURCE_RANGE: {source_start}-{source_end}")

        # Append checkpoint to volume: the commit point
        byte_start = VOL_PATH.stat().st_size if VOL_PATH.exists() else 0
        append_snapshot_text(body)
        byte_end = VOL_PATH.stat().st_size

        # Update operator state
        s.last_checkpoint_turn = s.total_turns
        s.last_checkpoint_id = snap_id

        _index_entry(warnings, snap_id, byte_start=byte_start, byte_end=byte_end,
                     operator=operator, timestamp=utc, snap_type="checkpoint")
        record = _ledger_record(warnings, snap_id, byte_start, byte_end, utc)

    print(f"[CHECKPOINT] Created {snap_id} for {operator} at turn {s.total_turns} ({len(compressed_summary)} chars)")

    # Save operator state after checkpoint creation
    _best_effort(warnings, "operator state", snap_id, save_operator_state)
    # The manifest's latest_* follow checkpoints too (audit O05-ledger-persistence-03).
    _best_effort(warnings, "ledger manifest", snap_id, publish_latest, record)
    _embed_and_store(warnings, snap_id, body)

    result = {"status": "created", "snap_id": snap_id, "model": model_used}
    if warnings:
        result["warnings"] = warnings
    return result


def should_create_checkpoint(operator: str) -> bool:
    """Check if a checkpoint should be created for this operator.

    Creates checkpoints when turns_since_last_checkpoint >= auto_create_interval.
    This matches the UI countdown timer (when it hits 0).

    A True answer CLAIMS the attempt (every caller creates the CHECKPOINT task
    on True): the attempt turn is recorded, and while that attempt is still
    running or after it failed, no new one is claimed until a full interval
    later (audit O05-ledger-persistence-15: a box whose compression call fails
    used to spawn a checkpoint task on every turn, forever).
    """
    s = get_state(operator)

    # Calculate turns since last checkpoint (this is what the UI countdown shows)
    turns_since_last_checkpoint = s.total_turns - s.last_checkpoint_turn
    turns_remaining = CHECKPOINT_AUTO_CREATE_INTERVAL - turns_since_last_checkpoint

    # Debug logging
    print(f"[CHECKPOINT-CHECK] Operator: {operator}, total_turns: {s.total_turns}, last_checkpoint_turn: {s.last_checkpoint_turn}")
    print(f"[CHECKPOINT-CHECK] Turns since last checkpoint: {turns_since_last_checkpoint}, Turns remaining: {turns_remaining}, Interval: {CHECKPOINT_AUTO_CREATE_INTERVAL}")

    # Create checkpoint when we've reached or exceeded the interval (countdown hits 0 or below)
    if turns_since_last_checkpoint < CHECKPOINT_AUTO_CREATE_INTERVAL:
        print(f"[CHECKPOINT-CHECK] Not yet - {turns_remaining} turns remaining until checkpoint")
        return False
    with _claim_lock:
        attempt = s.last_checkpoint_attempt_turn
        since_attempt = s.total_turns - attempt
        if attempt > s.last_checkpoint_turn and 0 <= since_attempt < CHECKPOINT_AUTO_CREATE_INTERVAL:
            print(f"[CHECKPOINT-CHECK] Due, but the attempt claimed at turn {attempt} is still running or failed; "
                  f"next attempt at turn {attempt + CHECKPOINT_AUTO_CREATE_INTERVAL}")
            return False
        s.last_checkpoint_attempt_turn = s.total_turns
    print(f"[CHECKPOINT-CHECK] Checkpoint needed! (counter hit 0)")
    return True

