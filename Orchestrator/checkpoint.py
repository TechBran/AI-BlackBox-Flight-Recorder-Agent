def _with_wellness(gauges: Dict[str, Any], wellness_gauge: str) -> Dict[str, Any]:
    """The mint's gauges, plus the WELLNESS tag when its turns carry one."""
    if wellness_gauge:
        gauges["wellness"] = wellness_gauge
    return gauges


# The ledger append is the commit point. Under mint_lock a mint only reads the
# tail, renders, appends, advances the operator's mint cursor, writes the
# index entry and records the ledger's prefix hash; the embed (bounded by the
# search layer's ceiling), the vector append, the manifest update and the
# state save run after the lock is released, best-effort, each failure
# reported in the result's "warnings" (audit O05-ledger-persistence-04/-05).
# A mint makes no archive copy: the maintenance pass makes one a day (audit
# rank 77).
def perform_mint(operator: str, reason: str = "MANUAL") -> Dict[str, Any]:
    # The ledger choke point: the operator is rendered verbatim into the body
    # ("OPERATOR: <name>", "operator=<name>"), so a name carrying a newline
    # would forge snapshot lines. Routes refuse it with a 400 first; this
    # raises InvalidOperatorName for any caller that did not.
    validate_operator(operator)
    verify_gm_or_halt()
    s = get_state(operator)
    warnings: List[str] = []

    with mint_lock:
        # The ledger's tail only (read_tail_text): every mint read and decoded
        # the whole ledger twice here (audit O05-ledger-persistence-18).
        info1 = parse_tail(read_tail_text(VOL_PATH))
        utc = now_utc_iso()
        snap_id = next_snap_id_from_tail(info1["tail_id"])

        new_items = s.conversation_log[s.last_mint_index:]

        # M1 location ride-along: same mechanism as `model` — the recording route
        # stashes it on last_context_meta; an empty string (the default, and what
        # a locationless turn writes) renders NOTHING anywhere.
        location_gauge = s.last_context_meta.get("location", "") or ""

        # Brandon 2026-07-25: "It should just be right before the operator. It
        # should be location, then operator, and then the user prompt right
        # there." So the turn's location is a FIELD ON THE LOG LINE, not only a
        # gauge in the header — that is the line anyone actually reads when they
        # open a snapshot. Absent location renders nothing at all, so a
        # locationless turn is byte-identical to before.
        loc_field = f"location={location_gauge} " if location_gauge else ""

        # M7 ledger rule: the turns since the last mint include one a wellness
        # result reached (its text was masked when it was recorded); the
        # snapshot carries the WELLNESS tag every ledger reader redacts by.
        # "" for every other snapshot: no gauge key, byte-identical.
        from Orchestrator.wellness.mask import gauge_text
        wellness_gauge = gauge_text(s.last_context_meta.get("wellness"))

        def _render_log_line(it: dict) -> str:
            if it.get("role") == "user":
                t = it.get("text", "")
            else:
                t = it.get("snap_text") or it.get("text", "")
            return f"{it['utc']} {loc_field}operator={operator} {it['role']}: {t}"

        log_lines = [_render_log_line(it) for it in new_items]

        usage_last = s.last_context_meta.get("usage_last", {})
        p = usage_last.get("prompt_tokens", 0)
        c = usage_last.get("completion_tokens", 0)
        t = usage_last.get("total_tokens", p + c)
        model_name = s.last_context_meta.get("model", "")
        drift = drift_state_for(s)

        gm_flag = s.last_context_meta.get("gm_excerpt", True)
        recent_ids = s.last_context_meta.get("recent_ids", [])
        relevant_ids = s.last_context_meta.get("relevant_ids", [])

        # DEBUG: Log what provenance is being saved to snapshot
        print(f"[MINT] Creating snapshot {snap_id} for operator {operator}")
        print(f"[MINT] Provenance - Recent: {recent_ids}")
        print(f"[MINT] Provenance - Relevant: {relevant_ids}")

        body = render_snapshot_body_v71(
            info1, snap_id, utc, reason, log_lines,
            gauges=_with_wellness({"drift": drift, "p": p, "c": c, "t": t, "model": model_name,
                                   "operator": operator, "location": location_gauge}, wellness_gauge),
            provenance={"gm": gm_flag, "recent": recent_ids, "relevant": relevant_ids},
        )

        info2 = parse_tail(read_tail_text(VOL_PATH))
        if info2["tail_id"] != info1["tail_id"]:
            info1 = info2
            snap_id = next_snap_id_from_tail(info1["tail_id"])
            body = render_snapshot_body_v71(
                info1, snap_id, utc, reason, log_lines,
                gauges=_with_wellness({"drift": drift, "p": p, "c": c, "t": t, "model": model_name,
                                       "operator": operator, "location": location_gauge}, wellness_gauge),
                provenance={"gm": gm_flag, "recent": recent_ids, "relevant": relevant_ids},
            )

        # Get file size before append to calculate byte offsets
        byte_start = VOL_PATH.stat().st_size if VOL_PATH.exists() else 0

        append_snapshot_text(body)

        # Get file size after append
        byte_end = VOL_PATH.stat().st_size if VOL_PATH.exists() else 0

        # Committed: these turns are in the ledger, so advance the cursor now,
        # before any later step can fail and get them minted a second time.
        s.last_mint_index = len(s.conversation_log)
        # M1: the location belonged to the turn just minted — consume it, so a
        # later mint on a route that never stamps one (cron /chat, CU, on-device)
        # can never inherit a stale fix.
        s.last_context_meta["location"] = ""
        # The WELLNESS tag belonged to the turns just minted, the same way.
        s.last_context_meta.pop("wellness", None)
        s.conv_turns_since  = 0
        s.conv_tokens_since = 0
        s.ctx_tokens_since  = 0
        s.context_used      = 0

        # Collect media artifacts from recent tasks for this operator
        # Lazy import to avoid circular dependency
        from Orchestrator.tasks import collect_pending_media_artifacts
        media_artifacts = _best_effort(warnings, "media artifacts", snap_id,
                                       collect_pending_media_artifacts, operator) or []
        if media_artifacts:
            print(f"[MINT] Collected {len(media_artifacts)} media artifact(s) for {snap_id}")

        # The snapshot's index entry (and media artifacts); vectors come after the lock.
        _index_entry(warnings, snap_id, byte_start, byte_end, operator, utc, snap_type="normal",
                     media_artifacts=media_artifacts if media_artifacts else None)
        record = _ledger_record(warnings, snap_id, byte_start, byte_end, utc)

    # Save operator state after mint
    _best_effort(warnings, "operator state", snap_id, save_operator_state)
    embed_dims = _embed_and_store(warnings, snap_id, body)
    # The record is the ledger as this mint committed it (byte_end, hashed
    # under mint_lock), never a later mint's half-written append.
    _best_effort(warnings, "ledger manifest", snap_id, publish_latest, record)

    result = _mint_result(snap_id, record, byte_end)
    # Vector-less mints (fresh box / soft failure) leave dims None and the
    # key is omitted from the result.
    if embed_dims is not None:
        result["dims"] = embed_dims
    if warnings:
        result["warnings"] = warnings
    return result


def mint_with_content(operator: str, content: str, reason: str = "DIRECT", snap_type: str = "normal") -> Dict[str, Any]:
    """Mint a snapshot with provided content (for MCP tools, CLI agents, etc.).

    Unlike perform_mint which pulls from conversation log, this creates a snapshot
    directly from the provided content string. Same commit-point ordering as
    perform_mint.

    Args:
        operator: The operator name (e.g., "Alice-DEV")
        content: The content to save in the snapshot
        reason: Reason for minting (e.g., "DIRECT", "MCP", "AGENT")
        snap_type: Type of snapshot ("normal", "checkpoint", "summary")

    Returns:
        Dict with snap_id and archive info ("warnings" lists any post-append
        step that failed)
    """
    validate_operator(operator)  # see perform_mint
    verify_gm_or_halt()
    warnings: List[str] = []

    with mint_lock:
        info1 = parse_tail(read_tail_text(VOL_PATH))
        utc = now_utc_iso()
        snap_id = next_snap_id_from_tail(info1["tail_id"])

        # Convert content to log lines format
        # Each line prefixed with timestamp and operator
        log_lines = [f"{utc} operator={operator} content: {content}"]

        print(f"[MINT-CONTENT] Creating snapshot {snap_id} for operator {operator}")
        print(f"[MINT-CONTENT] Content length: {len(content)} chars")

        body = render_snapshot_body_v71(
            info1, snap_id, utc, reason, log_lines,
            gauges={"drift": "green", "p": 0, "c": 0, "t": 0, "model": "direct-content", "operator": operator},
            provenance={"gm": False, "recent": [], "relevant": []},
        )

        # Handle race condition
        info2 = parse_tail(read_tail_text(VOL_PATH))
        if info2["tail_id"] != info1["tail_id"]:
            info1 = info2
            snap_id = next_snap_id_from_tail(info1["tail_id"])
            body = render_snapshot_body_v71(
                info1, snap_id, utc, reason, log_lines,
                gauges={"drift": "green", "p": 0, "c": 0, "t": 0, "model": "direct-content", "operator": operator},
                provenance={"gm": False, "recent": [], "relevant": []},
            )

        # Get file size before append
        byte_start = VOL_PATH.stat().st_size if VOL_PATH.exists() else 0

        append_snapshot_text(body)

        # Get file size after append
        byte_end = VOL_PATH.stat().st_size if VOL_PATH.exists() else 0

        # Update the snapshot index (vectors come after the lock)
        _index_entry(warnings, snap_id, byte_start, byte_end, operator, utc, snap_type=snap_type)
        record = _ledger_record(warnings, snap_id, byte_start, byte_end, utc)

    _embed_and_store(warnings, snap_id, body)
    _best_effort(warnings, "ledger manifest", snap_id, publish_latest, record)

    result = _mint_result(snap_id, record, byte_end)
    result["byte_range"] = [byte_start, byte_end]
    if warnings:
        result["warnings"] = warnings
    return result


