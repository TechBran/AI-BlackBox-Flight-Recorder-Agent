"""Media artifact retrieval — neutral module to avoid cross-route circular imports.

Single-responsibility module: query recent media artifacts (images, videos,
music) generated by completed tasks for a given operator. Extracted from
``Orchestrator/routes/chat_routes.py`` so that ``Orchestrator/context_builder.py``
(and future voice / agent-WS callers) can import it without pulling in the
chat-routes module graph. ``tasks.process_chat_task`` uses this same helper.

Per-operator scoping: an operator sees its OWN media plus ``"system"``-owned
media, merged by time. Media a chat tool loop generates is attributed to the
operator who asked for it (audit rank 49); ``"system"`` is box-scope work
(system cron jobs, and every row created before that fix), which stays
SHARED READ-ONLY: listed for every operator as something to reference, never
another operator's own media.
"""
from __future__ import annotations

from typing import Dict, List

from Orchestrator.models import TaskType, task_db

MEDIA_TASK_TYPES = (
    TaskType.IMAGE_GENERATION,
    TaskType.VIDEO_GENERATION,
    TaskType.LYRIA_MUSIC,
    TaskType.ELEVENLABS_MUSIC,
)
# The operator whose media every operator may reference (see module docstring).
SHARED_MEDIA_OPERATOR = "system"


def get_recent_media_artifacts(operator: str, limit: int = 10) -> List[Dict]:
    """Get recent media artifacts (images, videos, music) for an operator.

    Returns list of artifacts with URLs that the model can reference for
    subsequent operations like image-to-video conversion, newest first: the
    operator's own completed media and the shared system media, in one query
    (it used to keep only the first 50 rows of ALL the operator's tasks, so an
    operator with 50+ chat tasks never saw a system image).
    """
    tasks = task_db.get_recent_media_tasks(
        [operator, SHARED_MEDIA_OPERATOR], MEDIA_TASK_TYPES, limit)
    artifacts: List[Dict] = []
    for task in tasks:
        artifact = {
            "type": task.task_type.value.replace("_generation", "").replace("lyria_", ""),
            "url": task.result_url,
            "prompt": task.prompt[:100] if task.prompt else "",
            "task_id": task.task_id,
            "created_at": task.created_at,
        }

        # Include artifact metadata if available
        if task.result_data and "artifact" in task.result_data:
            artifact.update(task.result_data["artifact"])

        artifacts.append(artifact)
    return artifacts
