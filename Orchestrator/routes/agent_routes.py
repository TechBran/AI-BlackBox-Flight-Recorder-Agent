async def _inject_fossil_context(
    websocket: WebSocket,
    operator_raw: str,
    user_text: str,
    log_prefix: str,
) -> tuple[str, dict]:
    """Run shared retrieval and emit provenance to the client.

    Returns (fossil_context_str, provenance_dict). On any failure (or empty
    operator) returns an empty fossil string + empty provenance so the caller
    can proceed without context. Always emits a `provenance` WS frame so the
    client UI has a deterministic signal — even if every list is empty.
    """
    operator = resolve_operator(operator_raw, log_prefix)
    fossil_text, provenance = retrieve_for_agent(
        user_text=user_text,
        operator=operator,
        log_prefix=log_prefix,
    )
    # Ordering invariant: provenance MUST emit BEFORE we spawn Claude. Android's
    # ClaudeAgentClient writes provenance onto the *current* streaming UiMessage;
    # if we emit after stream completion, the event lands on the next bubble.
    await _safe_ws_send(websocket, {"type": "provenance", "data": provenance})
    return fossil_text, provenance


# Claude Code permission modes the agent surfaces offer (audit P03/O06). Only modes that
# actually work in non-interactive print mode (-p):
#   yolo — --dangerously-skip-permissions: every tool runs unattended (the long-standing default)
#   plan — read-only: --permission-mode plan, AND a tool set narrowed to PLAN_MODE_TOOLS
# There is deliberately no "ask before each tool" mode. Print mode has no stdin y/n protocol,
# so the old "Normal (prompts)" mode hung or auto-denied behind a fake approval dialog. It can
# come back only with a real approval round-trip (--permission-prompt-tool, or the stream-json
# control protocol).
PERMISSION_MODE_YOLO = "yolo"
PERMISSION_MODE_PLAN = "plan"

# Plan mode's whole tool set. ``--permission-mode plan`` on its own is NOT read-only here: the
# CLI still honours the user's and the project's settings in plan mode (this box's allow
# hundreds of Bash rules and run the auto-mode classifier), and a probe of the plan argv ran
# ``curl -X POST`` and ``wget --post-data`` with no denial. So plan also pins the built-in
# tools (``--tools``: a tool left out does not exist for the session, whatever a settings file
# allows), loads no MCP server (``--strict-mcp-config``: .mcp.json brings the BlackBox tools,
# which send mail and drive devices), and denies the mutating built-ins outright (deny rules
# beat allow rules). WebFetch is out too: a GET can still act on this box's own loopback API.
# Names this CLI build does not know are ignored (TodoWrite is gone from current builds).
PLAN_MODE_TOOLS = frozenset({"Read", "Grep", "Glob", "WebSearch", "TodoWrite"})
_PLAN_MODE_DENIED_TOOLS = ("Bash", "Edit", "Write", "NotebookEdit", "WebFetch")
_PERMISSION_MODE_ALIASES = {
    "yolo": PERMISSION_MODE_YOLO,
    "auto": PERMISSION_MODE_YOLO,   # the Portal's pre-2026-10 key for the same mode
    "plan": PERMISSION_MODE_PLAN,
}
UNSUPPORTED_APPROVAL_MESSAGE = (
    "This agent has no per-tool approval prompts. Switch the mode to Plan (read-only) or "
    "YOLO (every tool approved) and send the message again.")


def resolve_permission_mode(data: dict) -> str:
    """The permission mode a client frame asks for. Never escalates: the retired
    "normal"/"ask" mode, and anything unrecognised, resolve to the read-only plan mode.

    Clients send ``permission_mode``; a legacy client that sends only ``skip_permissions``
    keeps YOLO for ``true`` (or the flag absent, the old default) and gets plan for
    ``false`` (it asked for the approval mode that never worked)."""
    raw = data.get("permission_mode")
    if raw is not None:
        mode = _PERMISSION_MODE_ALIASES.get(str(raw).strip().lower())
        if mode is None:
            print(f"[AGENT] Unknown permission_mode {str(raw)[:40]!r} -> plan (read-only)")
            return PERMISSION_MODE_PLAN
        return mode
    return PERMISSION_MODE_YOLO if data.get("skip_permissions", True) is True else PERMISSION_MODE_PLAN


def build_claude_argv(claude_path: str, prompt: str, *, permission_mode: str,
                      model: str = None, claude_session_id: str = None,
                      resume_session: bool = False) -> List[str]:
    """The exact argv for a print-mode Claude Code run. Any mode other than yolo gets the
    read-only plan argv (fail safe): ``--permission-mode plan`` plus the pinned
    PLAN_MODE_TOOLS, no MCP servers and the mutating built-ins denied.

    The conversation is always named by id: ``--resume <id>`` continues it,
    ``--session-id <id>`` starts it under that id. There is no ``--continue``: it
    resumes the most recent conversation in the working directory, which every
    operator shares, so it could hand one operator another's transcript (audit
    O06-frontier-agent-13)."""
    cmd = [
        claude_path,
        "-p",  # Print mode - skips trust dialog
        "--output-format", "stream-json",  # Streaming JSON output
        "--verbose",  # Required for stream-json
    ]

    if permission_mode == PERMISSION_MODE_YOLO:
        cmd.append("--dangerously-skip-permissions")
    else:
        # --tools and --disallowedTools take a variadic list, so a boolean flag must follow
        # them: otherwise the CLI would read the prompt as one more tool name.
        cmd.extend([
            "--permission-mode", PERMISSION_MODE_PLAN,
            "--tools", ",".join(sorted(PLAN_MODE_TOOLS)),
            "--disallowedTools", ",".join(_PLAN_MODE_DENIED_TOOLS),
            "--strict-mcp-config",
        ])

    # Add model selection if specified
    if model:
        cmd.extend(["--model", model])

    # Session continuity: this conversation, by id
    if claude_session_id:
        cmd.extend(["--resume" if resume_session else "--session-id", claude_session_id])

    # Add the prompt
    cmd.append(prompt)
    return cmd


def _claude_path() -> str:
    """Path to the claude CLI: provider_bin (CLI_AGENT_CLAUDE_BIN, else PATH,
    ~/.local/bin and every nvm Node version), the bare name when not found."""
    from Orchestrator.routes.cli_agent_routes import provider_bin
    return provider_bin("claude") or "claude"


def _claude_child_path(claude_path: str) -> str:
    """The service PATH plus ~/.local/bin and the CLI's own dir (an nvm
    install's `#!/usr/bin/env node` shebang needs the node beside it)."""
    dirs = [os.environ.get("PATH", ""), os.path.expanduser("~/.local/bin")]
    if os.path.isabs(claude_path):
        dirs.append(os.path.dirname(claude_path))
    return ":".join(dict.fromkeys(dirs))


def claude_spawn_spec(working_dir: str, prompt: str, *, claude_session_id: str = None,
                      resume_session: bool = False, model: str = None,
                      permission_mode: str = PERMISSION_MODE_YOLO) -> SpawnSpec:
    """The print-mode Claude Code run for one agent turn; CliAgentTransport starts it.

    Uses -p (print) mode with stream-json output, which skips trust dialogs and
    interactive prompts.
    Args:
        working_dir: Working directory for Claude Code (a resumed conversation
            must run where it started: the CLI keeps conversations per directory)
        prompt: The prompt to send
        claude_session_id: The conversation's UUID
        resume_session: True resumes that conversation (--resume); False starts
            it under that id (--session-id)
        model: Model to use (opus, sonnet, haiku). If None, uses default.
        permission_mode: "yolo" (default, every tool approved) or "plan" (read-only).
    """
    claude_path = _claude_path()

    cmd = build_claude_argv(
        claude_path, prompt, permission_mode=permission_mode, model=model,
        claude_session_id=claude_session_id, resume_session=resume_session)

    print(f"[AGENT] Claude command: {' '.join(cmd[:8])}... (mode={permission_mode}, resume={resume_session}, session_id={claude_session_id[:8] if claude_session_id else 'None'})")
    print(f"[AGENT] Model specified: {model}")

    # Scrubbed env (shared env_scrub table): claude must authenticate with
    # the operator's subscription login, never bill an inherited
    # ANTHROPIC_API_KEY, and a YOLO agent must not hold the server's other
    # credentials (audit O14-cli-agents-devices-02/-03).
    env = {
        **scrubbed_child_env(),
        "PATH": _claude_child_path(claude_path),
    }
    return SpawnSpec(argv=cmd, cwd=working_dir, env=env)


def detect_agent_permission(text: str) -> Optional[Dict]:
    """Parse text for permission prompts from Claude Code.

    Returns:
        Dict with permission info if detected, None otherwise.
        If auto-approved, returns {"auto_approved": True, ...}
    """
    for pattern in AGENT_PERMISSION_PATTERNS:
        match = pattern.search(text)
        if match:
            prompt_text = match.group()

            # Check if this should be auto-approved (file reads)
            for auto_pattern in AGENT_AUTO_APPROVE_PATTERNS:
                if auto_pattern.search(text):
                    return {
                        "prompt_text": prompt_text,
                        "auto_approved": True
                    }

            # Determine action type
            action_type = "bash"
            lower_text = text.lower()
            if "edit" in lower_text or "write" in lower_text:
                action_type = "edit"
            elif "read" in lower_text:
                action_type = "read"

            return {
                "prompt_text": prompt_text,
                "action_type": action_type,
                "options": ["Allow", "Deny"],
                "auto_approved": False
            }
    return None


def detect_app_startup(text: str) -> Optional[Dict]:
    """Detect when Claude Code starts a local server.
    Returns:
        Dict with port and name if detected, None otherwise.
    """
    # Ports to exclude (system services)
    EXCLUDED_PORTS = {
        ORCHESTRATOR_PORT,  # AI BlackBox Orchestrator
        8080,  # Tailscale
        80,    # Standard HTTP
        443,   # Standard HTTPS
        22,    # SSH
        3000,  # Common dev server (often system-wide)
        5000,  # Common dev server (often system-wide)
    }

    patterns = [
        re.compile(r"listening on (?:http://)?localhost:(\d+)", re.I),
        re.compile(r"server.+(?:at|on).+localhost:(\d+)", re.I),
        re.compile(r"running (?:at|on).+localhost:(\d+)", re.I),
        re.compile(r"http://localhost:(\d+)"),
        re.compile(r"127\.0\.0\.1:(\d+)"),
    ]

    for pattern in patterns:
        match = pattern.search(text)
        if match:
            port = int(match.group(1))
            # Skip excluded ports
            if port in EXCLUDED_PORTS:
                continue
            return {
                "port": port,
                "name": f"App:{port}",
                "detected_at": now_utc_iso()
            }
    return None


