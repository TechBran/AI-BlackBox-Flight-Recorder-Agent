_PARTS = (_context, _media, _providers, _save, _cu, _stream, _nonstream)

for _part in _PARTS:
    for _name, _value in vars(_part).items():
        if not (_name.startswith("__") and _name.endswith("__")):
            globals()[_name] = _value
del _part, _name, _value


class _ChatRoutesNamespace(_types.ModuleType):
    """chat_routes' module type: setting (or deleting) a name here also sets it
    in every part that binds the name (see the module docstring)."""

    def __setattr__(self, name, value):
        super().__setattr__(name, value)
        for part in _PARTS:
            if name in part.__dict__:
                setattr(part, name, value)

    def __delattr__(self, name):
        super().__delattr__(name)
        for part in _PARTS:
            if name in part.__dict__:
                delattr(part, name)


_sys.modules[__name__].__class__ = _ChatRoutesNamespace
