OPERATOR_PREFERENCES: Dict[str, dict] = {}
# The dict is NEVER rebound: importers that bound it by value (tts_routes) and
# the lazy importers must all see the same object, so the loader clears and
# refills it (audit X05-architecture-05: the rebind orphaned tts_routes' copy
# and the Portal's preference syncs never reached disk). Mutate it through the
# accessors below, which hold _store_lock and persist.


def _valid_preferences(data) -> bool:
    return isinstance(data, dict) and all(isinstance(v, dict) for v in data.values())


def load_operator_preferences():
    """Load operator preferences from JSON file into the shared dict."""
    try:
        if not OPERATOR_PREFS_FILE.exists():
            print("[PREFS] No existing preferences file found, starting fresh")
            return
        # A corrupt file is quarantined (*.corrupt-<ts>) instead of being
        # overwritten by the next save with a near-empty dict.
        data = atomic_json.read_json(OPERATOR_PREFS_FILE, {}, valid=_valid_preferences)
        with _store_lock:
            OPERATOR_PREFERENCES.clear()
            OPERATOR_PREFERENCES.update(data)
        print(f"[PREFS] Loaded preferences for {len(OPERATOR_PREFERENCES)} operators")
    except Exception as e:
        print(f"[ERROR] Failed to load operator preferences: {e}")

def save_operator_preferences():
    """Save operator preferences to JSON file (atomic; a snapshot taken under
    the lock, so a concurrent setter can never tear the write)."""
    try:
        with _store_lock:
            atomic_json.write_json(OPERATOR_PREFS_FILE, copy.deepcopy(OPERATOR_PREFERENCES))
        print(f"[PREFS] Saved preferences for {len(OPERATOR_PREFERENCES)} operators")
    except Exception as e:
        print(f"[ERROR] Failed to save operator preferences: {e}")

def get_operator_preference(operator: str, key: str, default=None):
    """Get a specific preference for an operator."""
    prefs = OPERATOR_PREFERENCES.get(operator)
    if not isinstance(prefs, dict):
        return default
    return prefs.get(key, default)

def get_operator_preferences(operator: str) -> dict:
    """A copy of all of an operator's preferences ({} when none)."""
    with _store_lock:
        return copy.deepcopy(OPERATOR_PREFERENCES.get(operator) or {})

def set_operator_preference(operator: str, key: str, value):
    """Set a specific preference for an operator and persist."""
    merge_operator_preferences(operator, {key: value})

def merge_operator_preferences(operator: str, values: dict) -> dict:
    """Merge key/value pairs into an operator's preferences and persist.
    Returns a copy of the operator's preferences after the merge."""
    with _store_lock:
        OPERATOR_PREFERENCES.setdefault(operator, {}).update(values)
        save_operator_preferences()
        return copy.deepcopy(OPERATOR_PREFERENCES[operator])

def delete_operator_preference(operator: str, key: str) -> bool:
    """Remove one preference and persist. True when it was set."""
    with _store_lock:
        prefs = OPERATOR_PREFERENCES.get(operator)
        if not isinstance(prefs, dict) or key not in prefs:
            return False
        del prefs[key]
        save_operator_preferences()
        return True

