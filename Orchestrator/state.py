@dataclass
class OpState:
    conversation_log: list = field(default_factory=list)
    last_mint_index: int = 0
    conv_turns_since: int = 0
    conv_tokens_since: int = 0
    ctx_tokens_since: int = 0
    context_used: int = 0
    last_mint_ms: int = 0
    last_context_meta: dict = field(default_factory=lambda: {
        "recent_ids": [], "relevant_ids": [],
        "gm_excerpt": True, "model": "", "operator": "",
        "usage_last": {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0},
    })
    # Checkpoint tracking (per-operator)
    total_turns: int = 0  # Total conversation turns for this operator
    last_checkpoint_turn: int = 0  # Turn number of last checkpoint
    last_checkpoint_id: str = ""  # SNAP-ID of most recent checkpoint
    total_tokens: int = 0  # Cumulative token usage for this operator

    def add_conversation_turn(self, turn: dict, max_turns: int = 100):
        """Add a conversation turn with automatic pruning to prevent memory leaks"""
        self.conversation_log.append(turn)
        if len(self.conversation_log) > max_turns:
            items_removed = len(self.conversation_log) - max_turns
            old_index = self.last_mint_index
            self.conversation_log = self.conversation_log[-max_turns:]
            # Adjust last_mint_index to account for pruned items
            self.last_mint_index = max(0, self.last_mint_index - items_removed)

state_by_op: Dict[str, OpState] = defaultdict(OpState)

def get_state(op: str) -> OpState:
    return state_by_op[op or current_default()]

def save_operator_state():
    """Save persistent operator state to JSON file, including agent sessions."""
    try:
        state_data = {}
        for operator, state in list(state_by_op.items()):
            state_data[operator] = {
                "total_turns": state.total_turns,
                "last_checkpoint_turn": state.last_checkpoint_turn,
                "last_checkpoint_id": state.last_checkpoint_id,
                # Note: last_mint_index is not persisted since conversation_log is in-memory only
                "last_mint_ms": state.last_mint_ms,
                "total_tokens": state.total_tokens
            }

        # Also save agent session data for each operator
        # Look through AGENT_SESSIONS to find sessions by operator
        for session_id, session in list(AGENT_SESSIONS.items()):
            if session.operator and session.claude_session_id:
                if session.operator not in state_data:
                    state_data[session.operator] = {}
                state_data[session.operator]["agent_session"] = {
                    "claude_session_id": session.claude_session_id,
                    "message_count": session.message_count,
                    "model": session.model,
                    "working_directory": session.working_directory,
                    "last_activity": session.last_activity
                }

        # Also preserve any persisted agent sessions that aren't currently active
        for operator, persisted in list(PERSISTED_AGENT_SESSIONS.items()):
            if operator in state_data and "agent_session" not in state_data[operator]:
                state_data[operator]["agent_session"] = persisted

        with _store_lock:
            atomic_json.write_json(OPERATOR_STATE_FILE, state_data)
        print(f"[STATE] Saved operator state for {len(state_data)} operators")
    except Exception as e:
        print(f"[ERROR] Failed to save operator state: {e}")

def load_operator_state():
    """Load persistent operator state from JSON file, including agent sessions."""
    global PERSISTED_AGENT_SESSIONS
    try:
        if not OPERATOR_STATE_FILE.exists():
            print("[STATE] No existing operator state file found, starting fresh")
            return

        # A file that does not parse is quarantined (*.corrupt-<ts>), so the
        # next save cannot overwrite it; the box then starts fresh.
        state_data = atomic_json.read_json(OPERATOR_STATE_FILE, {}, valid=lambda d: isinstance(d, dict))

        for operator, data in state_data.items():
            if not isinstance(data, dict):
                continue
            s = get_state(operator)
            s.total_turns = data.get("total_turns", 0)
            s.last_checkpoint_turn = data.get("last_checkpoint_turn", 0)
            s.last_checkpoint_id = data.get("last_checkpoint_id", "")
            # Reset last_mint_index to 0 since conversation_log is empty after restart
            s.last_mint_index = 0
            s.last_mint_ms = data.get("last_mint_ms", 0)
            s.total_tokens = data.get("total_tokens", 0)

            # Load agent session data if present
            if "agent_session" in data:
                PERSISTED_AGENT_SESSIONS[operator] = data["agent_session"]
                print(f"[STATE]   {operator}: found persisted agent session (claude_id={data['agent_session'].get('claude_session_id', 'N/A')[:8]}..., msgs={data['agent_session'].get('message_count', 0)})")

        print(f"[STATE] Loaded operator state for {len(state_data)} operators")
        print(f"[STATE] Loaded {len(PERSISTED_AGENT_SESSIONS)} persisted agent sessions")
        for op, data in state_data.items():
            if isinstance(data, dict):
                print(f"[STATE]   {op}: {data.get('total_turns', 0)} turns, last checkpoint at turn {data.get('last_checkpoint_turn', 0)}")
    except Exception as e:
        print(f"[ERROR] Failed to load operator state: {e}")
        import traceback
        traceback.print_exc()

