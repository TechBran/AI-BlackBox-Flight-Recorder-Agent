"""Chat-created media belongs to the operator who asked for it (audit rank 49).

O02-chat-routes-A-03 / O03-chat-routes-B-10: every image / video / music task a
provider tool loop created was stamped operator="system" ("Placeholder, actual
operator set by UI" -- nothing ever set it). TaskDatabase.get_task_list
filters on the operator, so the requester's task pill and GET /tasks never
showed those generations, the completion notification was suppressed (system
tasks never notify), the Portal's isOwnTask check skipped the music toast,
and a token-bound MCP caller could not poll its own media task.

O05-ledger-persistence-14 / O04-tasks-retrieval-10: get_recent_media_artifacts
(two byte-identical copies, media.py and tasks.py) concatenated the
operator's WHOLE task history with the system history and cut to 50 before
filtering, so an operator with 50+ tasks never saw any system media, and the
window was not merged by time. It is now one SQL query.

Decision (documented in media.py): "system" media stays SHARED READ-ONLY --
tool media generated by box-scope work (system cron jobs, older rows) is
listed for every operator, while an operator's own media is listed only for
that operator.

Hermetic: create_task is a recorder for the chat loops, and the media query
runs against a fresh TaskDatabase under tmp_path.
"""
