def test_stream_anthropic_attributes_media_to_the_operator(cr, monkeypatch, tmp_path):
    from Orchestrator import provider_billing as pb

    monkeypatch.setattr(pb, "STATE_PATH", tmp_path / "billing.json")
    pb._reset_cache()

    def tool_events():
        events = [{"type": "message_start", "message": {"usage": {}}}]
        for i, (name, args) in enumerate(MEDIA_CALLS):
            events += [
                {"type": "content_block_start", "index": i,
                 "content_block": {"type": "tool_use", "id": f"tu_{i}", "name": name, "input": {}}},
                {"type": "content_block_delta", "index": i,
                 "delta": {"type": "input_json_delta", "partial_json": json.dumps(args)}},
                {"type": "content_block_stop", "index": i},
            ]
        return events + [{"type": "message_delta", "delta": {"stop_reason": "tool_use"}}]

    answer = [{"type": "content_block_start", "index": 0, "content_block": {"type": "text"}},
              {"type": "content_block_delta", "index": 0, "delta": {"type": "text_delta", "text": "ok"}},
              {"type": "content_block_stop", "index": 0},
              {"type": "message_delta", "delta": {"stop_reason": "end_turn"}}]
    scripts = [tool_events(), answer]

    class _Resp:
        status_code = 200

        def __init__(self, events):
            self._events = events

        async def aread(self):
            return b""

        async def aiter_lines(self):
            for e in self._events:
                yield f"data: {json.dumps(e)}"

    class _Ctx:
        def __init__(self, events):
            self._events = events

        async def __aenter__(self):
            return _Resp(self._events)

        async def __aexit__(self, *exc):
            return False

    class _Client:
        def __init__(self, *a, **k):
            pass

        async def __aenter__(self):
            return self

        async def __aexit__(self, *exc):
            return False

        def stream(self, method, url, headers=None, json=None):
            return _Ctx(scripts.pop(0))

    monkeypatch.setattr(cr.httpx, "AsyncClient", _Client)

    async def drain():
        return [e async for e in cr.stream_anthropic_with_thinking(
            [{"role": "user", "content": "make media"}], "claude-opus-5-5", OP)]

    events = asyncio.run(drain())
    assert events[-1]["type"] == "done"
    _assert_attributed(cr._created)
    pb._reset_cache()


