def parse_tail(vol_txt: str) -> Dict[str, Any]:
    ends = list(END_RX.finditer(vol_txt))
    if not ends:
        return {"unanimous": True, "tail_id": "SNAP-000", "utc": "N/A"}
    end_m = ends[-1]
    snap_id = end_m.group("snap")
    utc_part = end_m.group("utc")
    end_pos = end_m.start()
    starts_before = list(START_RX.finditer(vol_txt, 0, end_pos))
    start_m = next((m for m in reversed(starts_before) if m.group("snap") == snap_id), None)
    if not start_m:
        raise LedgerError("PARTIAL-SNAPSHOT")
    return {"unanimous": True, "tail_id": snap_id, "utc": utc_part}


# The first look at the ledger's end; it grows 4x until it holds the last
# snapshot whole (a long session's snapshot runs to a few hundred KB).
_TAIL_WINDOW = 64 * 1024


def _tail_resolved(text: str) -> bool:
    """True when `text` holds the last END marker and its own START before
    it, which is all parse_tail looks at."""
    end_m = None
    for end_m in END_RX.finditer(text):
        pass
    if end_m is None:
        return False
    snap_id = end_m.group("snap")
    return any(m.group("snap") == snap_id for m in START_RX.finditer(text, 0, end_m.start()))


def read_tail_text(p: Path) -> str:
    """The end of the ledger, enough of it for parse_tail: from a line start
    before the last snapshot's START marker to the end of the file.

    parse_tail of it answers exactly what parse_tail of the whole ledger
    does: the last END marker and its own START are both inside, and the
    window starts at a line boundary, so the line-anchored markers match as
    they do in the whole text. Every mint read and decoded the whole ledger
    twice under mint_lock just to find its tail (audit
    O05-ledger-persistence-18); this reads the last few KB. A ledger whose
    tail is torn (an END with no START) or has no END at all is read whole,
    so parse_tail still raises or returns SNAP-000 as before.
    """
    view = ledger.view(p)
    size = view.size
    window = _TAIL_WINDOW
    while True:
        lo = max(0, size - window)
        raw = view.read(lo, size)
        if lo > 0:
            # Start on a line boundary: a newline is never inside a UTF-8
            # sequence, and ^-anchored markers then match as in the whole text.
            nl = raw.find(b"\n")
            raw = raw[nl + 1:] if nl != -1 else b""
        text = raw.decode("utf-8", errors="replace")
        if lo == 0 or _tail_resolved(text):
            return text
        window *= 4

def next_snap_id_from_tail(tail_snap: str) -> str:
    today = datetime.now(timezone.utc).strftime("%Y%m%d")
    m = SNAP_RE.fullmatch(tail_snap.strip())
