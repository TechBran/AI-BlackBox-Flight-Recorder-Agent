def _cleanup_old_archives(days_to_keep, max_size_gb, max_files, min_free_gb, dry_run) -> Dict[str, Any]:
    cleanup_stats = {
        "deleted_files": 0,
        "deleted_size_mb": 0,
        "remaining_files": 0,
        "remaining_size_mb": 0,
        "reason": [],
        "dry_run": dry_run,
        "would_delete": [],
        "stale_temp_files": 0,
    }

    if not ARC_DIR.exists():
        return cleanup_stats

    # Leftovers of a killed archive write: the old *.part temp names and the
    # current hidden .Volume_*.tmp ones. Only stale ones; a fresh one may be
    # a write in flight.
    stale_cutoff = time.time() - _STALE_TEMP_S
    for pattern in ("Volume_*.part", ".Volume_*.tmp"):
        for leftover in ARC_DIR.glob(pattern):
            try:
                if leftover.stat().st_mtime >= stale_cutoff:
                    continue
                cleanup_stats["stale_temp_files"] += 1
                if not dry_run:
                    leftover.unlink()
            except OSError as e:
                print(f"Error removing archive temp file {leftover}: {e}")

    # Get all archive files sorted by modification time (oldest first)
    archive_files = []
    total_size = 0

    for file_path in ARC_DIR.glob("Volume_*.txt"):
        stat = file_path.stat()
        archive_files.append({
            "path": file_path,
            "mtime": stat.st_mtime,
            "size": stat.st_size
        })
        total_size += stat.st_size

    if not archive_files:
        return cleanup_stats

    # Sort by modification time (oldest first)
    archive_files.sort(key=lambda x: x["mtime"])

    # Determine what to delete
    files_to_delete = []
    cutoff_time = time.time() - (days_to_keep * 86400)  # Convert days to seconds

    # Check age-based cleanup
    for file_info in archive_files:
        if file_info["mtime"] < cutoff_time:
            files_to_delete.append(file_info)
            if "age" not in cleanup_stats["reason"]:
                cleanup_stats["reason"].append("age")

    # Check size-based cleanup (delete oldest until under size limit)
    total_size_gb = total_size / (1024 ** 3)
    if total_size_gb > max_size_gb:
        cleanup_stats["reason"].append("size")
        for file_info in archive_files:
            if total_size_gb <= max_size_gb:
                break
            if file_info not in files_to_delete:
                files_to_delete.append(file_info)
            total_size_gb -= (file_info["size"] / (1024 ** 3))

    # Check count-based cleanup (keep only the most recent max_files)
    if len(archive_files) > max_files:
        cleanup_stats["reason"].append("count")
        files_to_keep = archive_files[-max_files:]  # Keep the most recent
        for file_info in archive_files:
            if file_info not in files_to_keep and file_info not in files_to_delete:
                files_to_delete.append(file_info)

    # Free-space floor: delete further oldest copies (never the newest) until
    # the disk would have min_free_gb free after this cleanup.
    if min_free_gb > 0:
        floor = min_free_gb * GB
        free = _free_bytes(ARC_DIR) + sum(f["size"] for f in files_to_delete)
        for file_info in archive_files[:-1]:
            if free >= floor:
                break
            if file_info in files_to_delete:
                continue
            files_to_delete.append(file_info)
            free += file_info["size"]
            if "free_space" not in cleanup_stats["reason"]:
                cleanup_stats["reason"].append("free_space")

    cleanup_stats["would_delete"] = [f["path"].name for f in files_to_delete]

    # Perform deletion
    deleted = []
    if not dry_run:
        for file_info in files_to_delete:
            try:
                file_info["path"].unlink()
                deleted.append(file_info)
                cleanup_stats["deleted_files"] += 1
                cleanup_stats["deleted_size_mb"] += file_info["size"] / (1024 ** 2)
            except Exception as e:
                print(f"Error deleting archive {file_info['path']}: {e}")

    # Calculate remaining statistics
    gone = files_to_delete if dry_run else deleted
    remaining_size = 0
    remaining_count = 0
    for file_info in archive_files:
        if file_info not in gone:
            remaining_count += 1
            remaining_size += file_info["size"]

    cleanup_stats["remaining_files"] = remaining_count
    cleanup_stats["remaining_size_mb"] = remaining_size / (1024 ** 2)

    return cleanup_stats

