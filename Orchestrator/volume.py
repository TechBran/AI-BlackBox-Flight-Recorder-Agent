# Per-file caches for ledger_counts: path -> (file key, value).
_counts_cache: Dict[str, tuple] = {}


def _file_key(p: Path):
    try:
        st = p.stat()
    except OSError:
        return None
    return (st.st_ino, st.st_size, st.st_mtime_ns)


def _cached(name: str, p: Path, compute):
    """compute() once per version of the file or directory `p`."""
    key = _file_key(p)
    held = _counts_cache.get(name)
    if held is not None and held[0] == (str(p), key):
        return held[1]
    value = compute() if key is not None else None
    _counts_cache[name] = ((str(p), key), value)
    return value


def _hash_records_summary(p: Path) -> Dict[str, Any]:
    data = p.read_bytes()
    lines = [ln for ln in data.split(b"\n") if ln.strip()]
    last = None
    for raw in reversed(lines):
        try:
            last = json.loads(raw)
            break
        except ValueError:
            continue
    return {"count": len(lines), "last": last}


def _archive_summary() -> Dict[str, Any]:
    copies = []
    for p in ARC_DIR.glob("Volume_*.txt"):
        try:
            st = p.stat()
        except OSError:
            continue
        copies.append((st.st_mtime, st.st_size, p.name))
    copies.sort()
    newest = copies[-1] if copies else None
    return {"copies": len(copies), "bytes": sum(c[1] for c in copies),
            "newest": newest[2] if newest else None,
            "newest_utc": (datetime.fromtimestamp(newest[0], timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
                           if newest else None)}


def fsck_report_path() -> Path:
    """Manifest/ledger_fsck.json: the last ledger check (scripts/ledger_fsck.py
    --record, or the maintenance pass's daily run)."""
    from Orchestrator import ledger_fsck
    return MANIFEST.parent / ledger_fsck.REPORT_NAME


def ledger_counts(index: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """/health's ledger block: the ledger's size, how much of it the index
    covers, the prefix-hash records, the archive copies, and the last ledger
    check's counts. Each part is recomputed only when its file changes, so a
    /health poll costs a few stats (audit rank 77)."""
    from Orchestrator import ledger_fsck
    size = VOL_PATH.stat().st_size if VOL_PATH.exists() else 0
    out: Dict[str, Any] = {"bytes": size}
    if index is not None:
        held = _counts_cache.get("index")
        if held is not None and held[0] is index:
            indexed = held[1]
        else:
            indexed = max((int(m.get("byte_end", 0)) for m in index.values()), default=0)
            _counts_cache["index"] = (index, indexed)
        out["snapshots_indexed"] = len(index)
        out["indexed_bytes"] = indexed
        # Bytes past the last index entry: a snapshot appended but never
        # indexed (its index write failed), or an interrupted append.
        out["unindexed_tail_bytes"] = max(0, size - indexed)
    hashes = _cached("hashes", ledger_hashes_path(),
                     lambda: _hash_records_summary(ledger_hashes_path())) or {"count": 0, "last": None}
    out["hash_records"] = hashes["count"]
    out["last_hash_record"] = hashes["last"]
    archive = _cached("archive", ARC_DIR, _archive_summary) or {"copies": 0, "bytes": 0,
                                                              "newest": None, "newest_utc": None}
    out["archive_copies"] = archive["copies"]
    out["archive_bytes"] = archive["bytes"]
    out["newest_copy"] = archive["newest"]
    out["newest_copy_utc"] = archive["newest_utc"]
    report_path = fsck_report_path()
    out["fsck"] = _cached("fsck", report_path,
                          lambda: ledger_fsck.summary(ledger_fsck.read_report(report_path)))
    return out


def run_ledger_fsck(index: Optional[Dict[str, Any]] = None, record: bool = True) -> Dict[str, Any]:
    """Check the ledger (Orchestrator/ledger_fsck.py) against the index (the
    in-memory one when given), the prefix-hash records, the manifest and
    Archive/, and save the report for /health. Reads only the sizes it saw at
    the start, so a mint meanwhile is never mistaken for damage."""
    from Orchestrator import ledger_fsck
    if index is None:
        from Orchestrator.fossils import load_snapshot_index  # lazy: fossils imports this module
        index = load_snapshot_index()
    report = ledger_fsck.run(VOL_PATH, index, ledger_hashes_path(), MANIFEST, ARC_DIR,
                             size=_committed_size)
    if record:
        ledger_fsck.write_report(fsck_report_path(), report)
    return report


def ledger_fsck_due(interval_hours: Optional[float] = None, now: Optional[float] = None) -> bool:
    """True when the last saved ledger check is older than the copy interval
    (a day by default), or there is none."""
    interval = archive_copy_interval_hours() if interval_hours is None else interval_hours
    now = time.time() if now is None else now
    try:
        return now - fsck_report_path().stat().st_mtime >= interval * 3600
    except OSError:
        return True


