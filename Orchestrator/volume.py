def _copy_prefix(view: "ledger.LedgerView", upto: int, dest: Path) -> str:
    """Stream ledger[:upto] into `dest` (temp sibling, fsync, rename, directory
    fsync) and return its sha256, hashed from the bytes written: no 58 MB
    buffer. The temp name matches the stale-temp sweep's .Volume_*.tmp."""
    h = hashlib.sha256()
    fd, tmp = tempfile.mkstemp(dir=dest.parent, prefix=f".{dest.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as f:
            pos = 0
            while pos < upto:
                end = min(upto, pos + ledger.CHUNK)
                chunk = view.slice(pos, end)
                h.update(chunk)
                f.write(chunk)
                pos = end
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, dest)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    try:  # the rename itself is durable once the directory is
        dfd = os.open(dest.parent, os.O_RDONLY)
        try:
            os.fsync(dfd)
        finally:
            os.close(dfd)
    except OSError:
        pass
    return h.hexdigest()


def archive_volume(upto: Optional[int] = None):
    """Copy the committed ledger into Archive/ and list the copy in the
    manifest. Returns (copy path, sha256, utc).

    The maintenance pass calls this on a schedule (scheduled_archive_copy);
    mints no longer do (record_append). `upto` is a committed ledger size:
    those bytes are committed and, the ledger being append-only, never change,
    so the copy is exactly that ledger, never a torn one with a START and no
    END. Without `upto` the size is measured under mint_lock here (never call
    it so while holding mint_lock).

    Copies are cut under _archive_lock, and a request for an older committed
    prefix of the same ledger file than the newest copy holds is answered with
    that copy: the older prefix is already inside it. The copy streams from
    the ledger's map, hashed as it is written.
    """
    global _latest_copy, _latest_published
    if upto is None:
        upto = _committed_size()
    with _archive_lock:
        view = ledger.view(VOL_PATH)
        if view.size < upto:
            raise LedgerError(f"ARCHIVE-SHORT-READ: the ledger holds {view.size} bytes, "
                              f"{upto} were committed")
        ident = view.ident
        latest = _latest_copy
        if (latest is not None and latest[0] == ident and upto <= latest[1] <= view.size
                and Path(latest[2]).parent == ARC_DIR and Path(latest[2]).exists()):
            return Path(latest[2]), latest[3], latest[4]
        utc = now_utc_iso()
        ARC_DIR.mkdir(parents=True, exist_ok=True)
        floor = archive_min_free_gb() * GB
        free = _free_bytes(ARC_DIR)
        if free - upto < floor:
            raise LedgerError(
                f"ARCHIVE-SKIPPED-LOW-DISK: {free / GB:.2f} GB free, a {upto / GB:.2f} GB "
                f"copy would cross the {floor / GB:.2f} GB floor ([archive] min_free_gb)")
        arc = _archive_path(utc.replace(":", "-"))
        digest = _copy_prefix(view, upto, arc)
        man = _read_manifest()
        man["archive"].append({"utc": utc, "path": str(arc.as_posix()),
                               "sha256": digest, "bytes": upto})
        # A copy taken before any mint published a longer prefix describes
        # the newest committed ledger (a fresh process, or a box with no mints).
        published = _set_latest(man, ident, upto, digest, utc)
        _write_manifest(man)
        if published is not None:
            _latest_published = published
        _latest_copy = (ident, upto, str(arc), digest, utc)
    return arc, digest, utc


def _newest_copy() -> Optional[Dict[str, Any]]:
    newest = None
    if ARC_DIR.exists():
        for p in ARC_DIR.glob("Volume_*.txt"):
            try:
                st = p.stat()
            except OSError:
                continue
            if newest is None or st.st_mtime > newest["mtime"]:
                newest = {"path": p, "mtime": st.st_mtime, "size": st.st_size}
    return newest


def scheduled_archive_copy(interval_hours: Optional[float] = None,
                           now: Optional[float] = None) -> Dict[str, Any]:
    """The scheduled full copy of the ledger (the maintenance pass, hourly):
    one when the newest copy in Archive/ is older than [archive]
    copy_interval_hours (default a day) and the ledger has grown since it.
    An idle box gets no new copies, and every copy keeps the free-space floor
    (archive_volume raises ARCHIVE-SKIPPED-LOW-DISK below it). Returns what
    happened: {"copied": bool, "reason": ..., ...}."""
    interval = archive_copy_interval_hours() if interval_hours is None else interval_hours
    now = time.time() if now is None else now
    if not VOL_PATH.exists() or VOL_PATH.stat().st_size == 0:
        return {"copied": False, "reason": "no ledger"}
    newest = _newest_copy()
    if newest is not None and now - newest["mtime"] < interval * 3600:
        return {"copied": False, "reason": "not due", "newest": newest["path"].name}
    upto = _committed_size()
    if newest is not None and newest["size"] >= upto:
        return {"copied": False, "reason": "unchanged", "newest": newest["path"].name}
    arc, digest, utc = archive_volume(upto=upto)
    return {"copied": True, "reason": "due", "path": Path(arc).name, "sha256": digest,
            "bytes": upto, "utc": utc}


def _prune_manifest_archive(gone: List[Path], dry_run: bool) -> int:
    """Drop the manifest's archive[] entries whose copy no longer exists (or
    is being deleted), and put each remaining entry's time in ISO form. It
    used to list every copy ever made, 8,950 entries for 94 files (audit
    O05-ledger-persistence-03). Returns how many entries go. Under
    _archive_lock."""
    if not MANIFEST.exists():
        return 0
    man = _read_manifest(quarantine=not dry_run)
    gone_names = {p.name for p in gone}
    keep, dropped = [], 0
    for entry in man["archive"]:
        p = Path(entry.get("path", "")) if isinstance(entry, dict) else None
        if p is None or p.name in gone_names or not p.exists():
            dropped += 1
            continue
        keep.append(dict(entry, utc=_iso_utc(entry.get("utc", ""))))
    latest_utc = _iso_utc(man.get("latest_utc", ""))
    changed = dropped or keep != man["archive"] or latest_utc != man.get("latest_utc", "")
    if changed and not dry_run:
        man["archive"] = keep
        if "latest_utc" in man:
            man["latest_utc"] = latest_utc
        _write_manifest(man)
    return dropped


