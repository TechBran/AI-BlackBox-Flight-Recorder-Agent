def parse_tail(vol_txt: str) -> Dict[str, Any]:
    ends = list(END_RX.finditer(vol_txt))
    if not ends:
        return {"unanimous": True, "tail_id": "SNAP-000", "utc": "N/A"}
    end_m = ends[-1]
    snap_id = end_m.group("snap")
    utc_part = end_m.group("utc")
    end_pos = end_m.start()
    starts_before = list(START_RX.finditer(vol_txt, 0, end_pos))
    start_m = next((m for m in reversed(starts_before) if m.group("snap") == snap_id), None)
    if not start_m:
        raise LedgerError("PARTIAL-SNAPSHOT")
    return {"unanimous": True, "tail_id": snap_id, "utc": utc_part}

def next_snap_id_from_tail(tail_snap: str) -> str:
    today = datetime.now(timezone.utc).strftime("%Y%m%d")
    m = SNAP_RE.fullmatch(tail_snap.strip())
    n = int(m.group(2)) if m else 0
    n += 1
    width = max(3, len(str(n)))
    return f"SNAP-{today}-{str(n).zfill(width)}"

def append_snapshot_text(text: str):
    VOL_PATH.parent.mkdir(parents=True, exist_ok=True)
    try:
        with open(VOL_PATH, "rb+") as f:
            f.seek(0, os.SEEK_END)
            size = f.tell()
            if size > 0:
                f.seek(-1, os.SEEK_END)
                last = f.read(1)
                if last != b"\n":
                    f.seek(0, os.SEEK_END)
                    f.write(b"\n")
            f.write(text.encode("utf-8"))
            f.flush()
            os.fsync(f.fileno())
    except FileNotFoundError:
        with open(VOL_PATH, "wb") as f:
            f.write(text.encode("utf-8"))
            f.flush()
            os.fsync(f.fileno())

# archive_volume and cleanup_old_archives both rewrite Archive/ and the
# manifest; mints call archive_volume outside mint_lock, so they serialize here.
_archive_lock = threading.Lock()

GB = 1024 ** 3
# Archive/ temp files older than this are leftovers of a killed write.
_STALE_TEMP_S = 3600


def archive_min_free_gb() -> float:
    """config.ini [archive] min_free_gb (default 2): the free space the disk
    holding Archive/ must keep. A full-ledger archive copy that would cross it
    is skipped, and the cleanup deletes old copies until it is met, so the
    archive can never fill the disk the ledger appends to (audit
    O05-ledger-persistence-02). Read per call: an edit applies with no restart."""
    try:
        return max(0.0, CFG.getfloat("archive", "min_free_gb", fallback=2.0))
    except ValueError:
        return 2.0


def _free_bytes(directory: Path) -> int:
    probe = directory if directory.exists() else directory.parent
    return shutil.disk_usage(probe).free


def archive_volume():
    utc = now_utc_iso().replace(":", "-")
    arc = ARC_DIR / f"Volume_{utc}.txt"
    data = VOL_PATH.read_bytes()  # one read: the copy and its digest match
    with _archive_lock:
        ARC_DIR.mkdir(parents=True, exist_ok=True)
        floor = archive_min_free_gb() * GB
        free = _free_bytes(ARC_DIR)
        if free - len(data) < floor:
            raise LedgerError(
                f"ARCHIVE-SKIPPED-LOW-DISK: {free / GB:.2f} GB free, a {len(data) / GB:.2f} GB "
                f"copy would cross the {floor / GB:.2f} GB floor ([archive] min_free_gb)")
        atomic_write(arc, data)
        man = json.loads(MANIFEST.read_text())
        digest = sha256_bytes(data)
        man["latest_path"] = str(VOL_PATH.as_posix())
        man["latest_sha256"] = digest
        man["latest_utc"] = utc.replace("-", ":", 2)
        man["archive"].append({"utc": utc.replace("-", ":", 2),
                               "path": str(arc.as_posix()),
                               "sha256": digest})
        atomic_write(MANIFEST, json.dumps(man, indent=2).encode("utf-8"))
    return arc, digest, utc

def cleanup_old_archives(days_to_keep: int = 30, max_size_gb: float = 5.0, max_files: int = 200,
                         *, min_free_gb: float = 0.0, dry_run: bool = False) -> Dict[str, Any]:
    """Clean up old archive files to prevent disk space issues.

    Args:
        days_to_keep: Keep archives newer than this many days
        max_size_gb: Maximum total size of archive directory in GB
        max_files: Maximum number of archive files to keep
        min_free_gb: Free-space floor for the disk holding Archive/: while it
            is not met, the oldest remaining copies are deleted too. The
            newest copy is never deleted for it.
        dry_run: Compute and report what would be deleted; delete nothing
            (audit O05-ledger-persistence-10: it used to delete for real)

    Returns:
        Dict with cleanup statistics ("would_delete" lists the file names)
    """
