def record_append(snap_id: str, byte_start: int, byte_end: int, utc: Optional[str] = None,
                  ledger_path: Optional[Path] = None) -> Optional[Dict[str, Any]]:
    """Record one append to the ledger: its snapshot, its byte range, and the
    sha256 of the whole ledger up to its end, as one line of
    Manifest/ledger_hashes.jsonl. Returns the record (None when nothing was
    appended: no ledger, or no growth).

    Every writer calls it under mint_lock right after its append (mints,
    mint_with_content, checkpoints, flight reports), so the records follow
    the appends in order and each one hashes only the bytes since the last
    (PrefixHasher). This replaces the full copy of the ledger every mint
    wrote into Archive/ (audit O05-ledger-persistence-02: 58 MB per mint, up
    to 1 GB a day): the ledger is append-only, so the archive a mint used to
    write is exactly ledger[:byte_end], and its hash here proves it. Each
    record's byte_start is the previous one's byte_end, so the records form a
    chain scripts/ledger_fsck.py verifies; full copies are now scheduled
    (scheduled_archive_copy).
    """
    path = Path(ledger_path) if ledger_path is not None else VOL_PATH
    if byte_end <= byte_start or not path.exists():
        return None
    view = ledger.view(path)
    if byte_end > view.size:
        raise LedgerError(f"RECORD-PAST-EOF: the ledger holds {view.size} bytes, "
                          f"the append ends at {byte_end}")
    record = {
        "snap_id": snap_id,
        "byte_start": int(byte_start),
        "byte_end": int(byte_end),
        "sha256": _PREFIX.digest_upto(view, byte_end),
        "utc": utc or now_utc_iso(),
    }
    line = (json.dumps(record, separators=(",", ":")) + "\n").encode("utf-8")
    out = ledger_hashes_path()
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "ab") as f:
        # A torn last line (a crash mid-write) gets its own line ending, so
        # this record is never glued onto it.
        if os.fstat(f.fileno()).st_size > 0:
            with open(out, "rb") as r:
                r.seek(-1, os.SEEK_END)
                if r.read(1) != b"\n":
                    f.write(b"\n")
        f.write(line)
        f.flush()
        os.fsync(f.fileno())
    record["ledger"] = list(view.ident)
    return record


def publish_latest(record: Optional[Dict[str, Any]]) -> bool:
    """Point the manifest's latest_* (path, sha256, utc, bytes, snap_id) at a
    record_append record. Writers call it after releasing mint_lock; an older
    record finishing after a newer one never moves latest_* back. All four
    writers do (checkpoints and flight reports never refreshed latest_sha256,
    audit O05-ledger-persistence-03), and latest_utc is the ISO time."""
    if not record:
        return False
    global _latest_published
    ident = tuple(record.get("ledger") or ledger.view(VOL_PATH).ident)
    with _archive_lock:
        man = _read_manifest()
        published = _set_latest(man, ident, record["byte_end"], record["sha256"], record["utc"],
                                record.get("snap_id"))
        if published is None:
            return False
        _write_manifest(man)
        _latest_published = published
    return True


