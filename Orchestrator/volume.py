def read_text_safe(p: Path) -> str:
    """Read file with fresh handle to avoid caching issues.

    On Windows, file system caching can cause stale reads when files are
    rapidly appended. Read in binary mode first, then decode to ensure
    we get ALL bytes from disk, not a buffered/cached subset.
    """
    if not p.exists():
        return ""

    # Read in binary mode to ensure complete file read, then decode
    # Text mode reads can be incomplete due to buffering on Windows
    try:
        with open(p, 'rb') as f:
            raw_bytes = f.read()

        # Decode with error replacement
        text = raw_bytes.decode('utf-8', errors='replace')

        # Debug: verify we read the complete file
        expected_size = p.stat().st_size
        actual_size = len(raw_bytes)
        if actual_size != expected_size:
            print(f"[ERROR] Incomplete read! Expected {expected_size} bytes, got {actual_size} bytes")

        return text
    except Exception as e:
        print(f"[ERROR] Failed to read {p}: {e}")
        import traceback
        traceback.print_exc()
        return ""

