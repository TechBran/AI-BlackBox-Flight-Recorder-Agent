def cleanup_old_artifacts():
    """Remove artifacts older than ARTIFACT_RETENTION_DAYS."""
    if not ARTIFACTS_DIR.exists():
        return
    cutoff = time.time() - (ARTIFACT_RETENTION_DAYS * 86400)
    cleaned = 0
    for artifact in ARTIFACTS_DIR.iterdir():
        if artifact.is_file() and artifact.stat().st_mtime < cutoff:
            try:
                artifact.unlink()
                cleaned += 1
                print(f"[ARTIFACT] Cleaned up expired: {artifact.name}")
            except Exception as e:
                print(f"[ARTIFACT] Cleanup error: {e}")
    if cleaned:
        print(f"[ARTIFACT] Cleaned up {cleaned} expired artifacts")

