#!/bin/bash
# Setup polkit rule to allow the BlackBox service to control NetworkManager
# connections (cellular deep-reconnect).
# Run this once with: sudo bash Scripts/setup-cellular-polkit.sh [service-user]
# (install.sh re-runs it automatically on a box where the rule is installed.)
#
# The rule grants exactly ONE polkit action, and only to the service user:
#   org.freedesktop.NetworkManager.network-control — activate / deactivate a
#   connection. The only in-service NetworkManager write is
#   Orchestrator/cellular/internet_manager.py deep_reconnect's
#   `nmcli connection down`; APN changes are made by Scripts/auto-apn.sh, which
#   runs as root and needs no rule.
#
# 2026-10 audit X06-ops-deploy-09 / O22-06: the previous rule also returned YES
# for org.freedesktop.systemd1.manage-units (start/stop ANY unit, including
# transient units — `systemd-run` as root from any code in the service) and for
# every org.freedesktop.NetworkManager.* action. Both are gone; nothing in the
# service restarts ModemManager or edits NetworkManager settings.
#
# Service user: $1, else blackbox.service's User=, else $SUDO_USER, else the
# invoking user — validated as a POSIX username and never root. (The old
# `$(systemctl show … || id -un)` never fell back: systemctl prints an empty
# value with rc 0 when the unit has no User=, which produced a rule for "".)
#
# POLKIT_RULES_DIR is overridable ONLY so scripts/tests/test_cellular_polkit_rule.sh
# can render the rule into a mktemp sandbox; polkit is restarted only when the
# real rules.d is written.

set -euo pipefail

RULES_DIR="${POLKIT_RULES_DIR:-/etc/polkit-1/rules.d}"
RULES_FILE="$RULES_DIR/10-blackbox-networkmanager.rules"

SERVICE_USER="${1:-}"
if [[ -z "$SERVICE_USER" ]]; then
    SERVICE_USER="$(systemctl show blackbox.service -p User --value 2>/dev/null || true)"
fi
[[ -n "$SERVICE_USER" ]] || SERVICE_USER="${SUDO_USER:-}"
[[ -n "$SERVICE_USER" ]] || SERVICE_USER="$(id -un)"

# The name is interpolated into JavaScript below, so it must be a plain POSIX
# username; a rule for root would be meaningless (root needs no polkit grant).
if ! [[ "$SERVICE_USER" =~ ^[a-z_][a-z0-9_-]*$ ]] || [[ "$SERVICE_USER" == "root" ]]; then
    echo "[setup-cellular-polkit] ERROR: refusing service user '$SERVICE_USER' (need a non-root POSIX username)" >&2
    echo "[setup-cellular-polkit] Usage: sudo bash Scripts/setup-cellular-polkit.sh <service-user>" >&2
    exit 1
fi

echo "Creating polkit rule for user: $SERVICE_USER"
echo "File: $RULES_FILE"

mkdir -p "$RULES_DIR"

# Write a temp file in the same dir, then rename it over the rule, so polkitd
# (which watches rules.d and loads only *.rules) never reads a half-written rule.
TMP_RULE="$(mktemp "$RULES_DIR/.blackbox-networkmanager.XXXXXX")"
trap 'rm -f "${TMP_RULE:-}"' EXIT
cat > "$TMP_RULE" << POLKIT_EOF
// Generated by BlackBox Scripts/setup-cellular-polkit.sh — DO NOT EDIT BY HAND.
// Lets the BlackBox service user activate/deactivate NetworkManager
// connections (cellular deep-reconnect: \`nmcli connection down\`). Nothing
// else: no systemd unit management, no NetworkManager settings changes.
polkit.addRule(function(action, subject) {
    if (subject.user !== "$SERVICE_USER") return undefined;

    if (action.id === "org.freedesktop.NetworkManager.network-control") {
        return polkit.Result.YES;
    }
    return undefined;
});
POLKIT_EOF
chmod 0644 "$TMP_RULE"
mv -f "$TMP_RULE" "$RULES_FILE"

echo "Polkit rule created successfully."
if [[ "$RULES_DIR" == "/etc/polkit-1/rules.d" ]]; then
    # polkitd also reloads rules.d on change; the restart is belt-and-braces,
    # so its failure must not fail a rule that is already written.
    echo "Restarting polkit..."
    systemctl restart polkit || echo "WARN: polkit restart failed; polkitd picks up rules.d changes on its own" >&2
fi
echo "Done. The BlackBox service user can now activate/deactivate NetworkManager connections."
