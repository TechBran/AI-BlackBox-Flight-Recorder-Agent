#!/usr/bin/env bash
# Regenerate the Orchestrator venv's lock from requirements.in.
#
#   scripts/compile_python_lock.sh              rewrite requirements.lock.txt + requirements.txt
#   scripts/compile_python_lock.sh -P aiohttp   also upgrade one package (extra args go to uv)
#   scripts/compile_python_lock.sh --check      exit 1 if either file is out of date (CI gate)
#
# The committed lock seeds the resolver's preferences, so a recompile keeps
# every validated pin that still satisfies requirements.in and moves only what
# a changed floor or cap forces, or what -P / --upgrade asks for. Run the
# targeted tests (and pip-audit) against a venv built from the new lock before
# committing it.
#
# requirements.lock.txt  every package, == pinned, with sha256 hashes. Installed
#                        with `pip install --require-hashes -r` by
#                        Scripts/install.sh and Orchestrator/update/runner.py.
# requirements.txt       the same pins without hashes (rendered from the lock,
#                        not re-resolved), for installs that cannot use hash
#                        mode.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
UV="${UV:-uv}"
UV_VERSION="0.13.1"     # lock output differs between uv releases; CI pins the same
PYTHON_VERSION="3.12"   # the boxes' interpreter (Scripts/install.sh builds with python3.12)
SELF="scripts/compile_python_lock.sh"

check=0
if [[ "${1:-}" == "--check" ]]; then
    check=1
    shift
fi
if (( check )) && (( $# )); then
    echo "ERROR: --check takes no other arguments" >&2
    exit 2
fi

if ! command -v "$UV" > /dev/null 2>&1; then
    echo "ERROR: uv not found. Install it with: python3 -m pip install uv==$UV_VERSION (or set UV=/path/to/uv)" >&2
    exit 2
fi
have="$("$UV" --version | awk '{print $2}')"
if [[ "$have" != "$UV_VERSION" ]]; then
    echo "ERROR: uv $have found, uv $UV_VERSION required: the lock's layout differs between uv releases." >&2
    echo "       python3 -m pip install uv==$UV_VERSION (or set UV=/path/to/uv)" >&2
    exit 2
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

if [[ -f "$ROOT/requirements.lock.txt" ]]; then
    cp "$ROOT/requirements.lock.txt" "$tmp/requirements.lock.txt"
fi

# Relative input path, so the lock's "# via -r requirements.in" lines do not
# depend on where the repo is checked out.
(cd "$ROOT" && "$UV" pip compile requirements.in \
    --generate-hashes \
    --python-version "$PYTHON_VERSION" \
    --custom-compile-command "$SELF" \
    --quiet \
    -o "$tmp/requirements.lock.txt" "$@")

{
    echo "# GENERATED by $SELF from requirements.in. Do not edit: change"
    echo "# requirements.in and re-run the script."
    echo "#"
    echo "# The pins of requirements.lock.txt without their hashes, for installs that"
    echo "# cannot use hash mode (pip install -r requirements.txt -r requirements.dev.txt,"
    echo "# or an updater that predates the lock). Boxes install requirements.lock.txt"
    echo "# with --require-hashes."
    awk '/^[A-Za-z0-9]/ { sub(/ *\\$/, ""); print }' "$tmp/requirements.lock.txt"
} > "$tmp/requirements.txt"

if (( check )); then
    rc=0
    for f in requirements.lock.txt requirements.txt; do
        if ! diff -u "$ROOT/$f" "$tmp/$f" > "$tmp/$f.diff" 2>&1; then
            echo "ERROR: $f is out of date with requirements.in. Run $SELF and commit the result." >&2
            head -n 60 "$tmp/$f.diff" >&2
            rc=1
        fi
    done
    if (( rc == 0 )); then
        echo "OK: requirements.lock.txt and requirements.txt match requirements.in"
    fi
    exit "$rc"
fi

cp "$tmp/requirements.lock.txt" "$ROOT/requirements.lock.txt"
cp "$tmp/requirements.txt" "$ROOT/requirements.txt"
echo "Wrote requirements.lock.txt and requirements.txt ($(grep -c '^[A-Za-z0-9]' "$ROOT/requirements.txt") packages)"
